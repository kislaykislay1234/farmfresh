let activeAudioElement = null

/**
 * Play Base64 Audio data (WAV) generated by Sarvam AI TTS
 * @param {string} base64Audio
 * @returns {Promise<HTMLAudioElement>}
 */
export const playBase64Audio = (base64Audio) => {
  return new Promise((resolve, reject) => {
    try {
      if (!base64Audio) {
        resolve(null)
        return
      }

      if (activeAudioElement) {
        activeAudioElement.pause()
        activeAudioElement.currentTime = 0
      }

      const audioSrc = base64Audio.startsWith('data:')
        ? base64Audio
        : `data:audio/wav;base64,${base64Audio}`

      const audio = new Audio(audioSrc)
      activeAudioElement = audio

      audio.onended = () => {
        activeAudioElement = null
        resolve(audio)
      }

      audio.onerror = (e) => {
        activeAudioElement = null
        reject(e)
      }

      audio.play().catch(reject)
    } catch (err) {
      reject(err)
    }
  })
}

/**
 * Stop any currently playing audio
 */
export const stopActiveAudio = () => {
  if (activeAudioElement) {
    activeAudioElement.pause()
    activeAudioElement.currentTime = 0
    activeAudioElement = null
  }
}

/**
 * Convert Text to Speech using Sarvam AI TTS (Bulbul v3 - 11 languages supported)
 * @param {string} text
 * @param {string} languageCode - e.g. "hi-IN", "gu-IN", "ta-IN"
 * @returns {Promise<{ audio_base64: string|null, unsupported?: boolean }>}
 */
export const convertTextToSpeech = async (text, languageCode = 'hi-IN') => {
  const sarvamLang = SARVAM_LANG_MAP[languageCode] || languageCode

  // Bulbul v3 TTS constraint: only 11 languages supported
  if (!isTtsSupported(sarvamLang)) {
    return {
      audio_base64: null,
      unsupported: true,
      message: `Spoken reply isn't available in this language yet (${sarvamLang}) — showing text instead.`
    }
  }

  // 1. Try Supabase Edge Function if connected
  if (supabase?.functions) {
    try {
      const { data, error } = await supabase.functions.invoke('tts-proxy', {
        body: { text, language_code: sarvamLang },
      })
      if (!error && data?.audio_base64) {
        return data
      }
    } catch (edgeErr) {
      console.warn('Edge TTS proxy bypass, using direct API:', edgeErr)
    }
  }

  // 2. Direct Sarvam AI Endpoint with key
  try {
    const response = await fetch('https://api.sarvam.ai/text-to-speech', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'api-subscription-key': SARVAM_API_KEY,
      },
      body: JSON.stringify({
        text: text.slice(0, 500),
        language_code: sarvamLang,
      }),
    })

    if (!response.ok) {
      const errData = await response.json().catch(() => ({}))
      console.warn('Sarvam TTS API response not ok:', errData)
      return { audio_base64: null }
    }

    const data = await response.json()
    return {
      audio_base64: data.audios?.[0] || null,
      request_id: data.request_id,
    }
  } catch (err) {
    console.warn('Sarvam TTS error:', err)
    return { audio_base64: null }
  }
}

/**
 * Translate Text to any of the 22 Indian languages
 * @param {string} text
 * @param {string} targetLang - e.g. "hi-IN", "gu-IN", "ta-IN"
 * @param {string} [sourceLang="en-IN"]
 * @returns {Promise<string>}
 */
export const translateText = async (text, targetLang = 'hi-IN', sourceLang = 'en-IN') => {
  const targetCode = SARVAM_LANG_MAP[targetLang] || targetLang
  const sourceCode = SARVAM_LANG_MAP[sourceLang] || sourceLang

  if (targetCode === sourceCode || !text.trim()) {
    return text
  }

  // 1. Try Supabase Edge Function
  if (supabase?.functions) {
    try {
      const { data, error } = await supabase.functions.invoke('translate-proxy', {
        body: { text, targetLang: targetCode, sourceLang: sourceCode },
      })
      if (!error && data?.translated) {
        return data.translated
      }
    } catch (edgeErr) {
      console.warn('Edge translate proxy bypass, using direct API:', edgeErr)
    }
  }

  // 2. Direct Sarvam AI Translate
  try {
    const response = await fetch('https://api.sarvam.ai/translate', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'api-subscription-key': SARVAM_API_KEY,
      },
      body: JSON.stringify({
        input: text,
        source_language_code: sourceCode,
        target_language_code: targetCode,
        mode: 'modern-colloquial',
      }),
    })

    if (!response.ok) {
      return text
    }

    const data = await response.json()
    return data.translated_text || text
  } catch (err) {
    console.warn('Translate error:', err)
    return text
  }
}

